settings = Settings()
_WEAK_SECRETS = {'change-me-in-production','change_me_in_production','change_me_to_a_long_random_string','change_me','change-me'}
_AUTOGEN_PREFIX = 'valsec-autogen-'

def _secret_is_weak():
    value=settings.SECRET_KEY.strip()
    return value in _WEAK_SECRETS or 'change' in value.lower() or len(value)<32

def _credential_vault_key_is_weak():
    value=settings.CREDENTIAL_VAULT_KEY.strip()
    return not value or value in _WEAK_SECRETS or 'change' in value.lower() or len(value)<32

def is_production():
    return settings.VALSEC_ENV.strip().lower() in {'production','prod'} or settings.REQUIRE_AUTH or settings.SESSION_COOKIE_SECURE

def _secret_key_file():
    return Path(__file__).resolve().parent.parent/'.secret_key'

def secret_is_autogenerated():
    return settings.SECRET_KEY.strip().startswith(_AUTOGEN_PREFIX)

def ensure_secret_key():
    if not _secret_is_weak() or is_production(): return
    path=_secret_key_file()
    try:
        existing=path.read_text().strip() if path.exists() else ''
        if existing:
            settings.SECRET_KEY=existing
            return
        settings.SECRET_KEY=_AUTOGEN_PREFIX+secrets.token_urlsafe(48)
        path.write_text(settings.SECRET_KEY)
        path.chmod(0o600)
    except OSError:
        settings.SECRET_KEY=_AUTOGEN_PREFIX+secrets.token_urlsafe(48)

def validate_startup_security():
    problems=[]
    if _secret_is_weak(): problems.append('SECRET_KEY must be at least 32 characters and must not be a placeholder')
    if settings.ENABLE_CREDENTIAL_VAULT and _credential_vault_key_is_weak():
        problems.append('CREDENTIAL_VAULT_KEY must be at least 32 characters and must not be a placeholder')
    if 'valsec_local_change_me' in settings.DATABASE_URL: problems.append('DATABASE_URL contains the shipped local PostgreSQL password')
    if secret_is_autogenerated() and is_production(): problems.append('Set an explicit SECRET_KEY for production')
    if not problems: return
    if is_production(): raise RuntimeError(f'Refusing insecure production startup (VALSEC_ENV={settings.VALSEC_ENV}): '+'; '.join(problems))
    log=logging.getLogger('valsec.startup')
    for problem in problems: log.warning('Local development default: %s',problem)
