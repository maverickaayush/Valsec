import logging
import secrets
from pydantic_settings import BaseSettings, SettingsConfigDict

class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file='.env', env_file_encoding='utf-8', extra='ignore')
    DATABASE_URL: str = 'postgresql://valsec:valsec_local_change_me@localhost:5432/valsec'
    REDIS_URL: str = 'redis://localhost:6379/0'
    OLLAMA_URL: str = 'http://localhost:11434'
    OLLAMA_AUTH_TOKEN: str = ''
    INFERENCE_TIMEOUT_MULTIPLIER: float = 1.5
    MAX_CONCURRENT_AUDITS: int = 5
    ENABLE_CREDENTIAL_VAULT: bool = False
    CREDENTIAL_VAULT_KEY: str = ''
    DISCOVERY_MAX_DEPTH: int = 3
    DISCOVERY_MAX_DEVICES: int = 25
    OLLAMA_MAPPING_BATCH_SIZE: int = 24
    OLLAMA_MAPPING_MAX_CANDIDATES: int = 96
    SECRET_KEY: str = 'change-me-in-production'
    VALSEC_ENV: str = 'development'
    ALLOWED_HOSTS: str = 'localhost,127.0.0.1'
    CORS_ORIGINS: str = 'http://localhost:3000,http://127.0.0.1:3000'
    REQUIRE_AUTH: bool = False
    PASSWORD_MIN_LENGTH: int = 10
    SESSION_TTL_HOURS: int = 72
    SESSION_COOKIE_NAME: str = 'valsec_session'
    SESSION_COOKIE_SECURE: bool = False
    SESSION_COOKIE_SAMESITE: str = 'lax'
    SESSION_COOKIE_DOMAIN: str = ''
    OTP_TTL_SECONDS: int = 300
